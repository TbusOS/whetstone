# Every rule is exercised in both directions: the case it must act on, and the
# nearest case it must leave alone.
#
# Why the export is tested with route: route reads nothing but the event lines, so a
# wrong line from the adapter (a tool result taken for something the user typed, a
# SKILL.md edit taken for a use) becomes a wrong table with no error anywhere.
#
#   bash bin/route_selftest.sh
