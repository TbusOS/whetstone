pass=0; fail=0
ok()  { pass=$((pass+1)); echo "  ok  - $1"; }
bad() { fail=$((fail+1)); echo "  FAIL- $1"; }
# python checks print "ok  - ..." / "FAIL- ..." lines; count them here
tally() {
  local line
  while IFS= read -r line; do
    case "$line" in
      "ok  - "*) ok "${line#ok  - }" ;;
      "FAIL- "*) bad "${line#FAIL- }" ;;
      *) bad "unexpected output: $line" ;;
    esac
  done
}

