#!/usr/bin/env bash
# Selftest for bin/deploy.sh — the argument parser first, because that is where it
# once failed silently: `deploy.sh --gen-claudemd` with the value left off spun at
# 100% CPU for 76.5 hours (2026-08-31 .. 09-03) with no output, no memory, no I/O.
# `shift 2` with one argument left fails and shifts nothing, so `$#` never drops.
# Every value-taking option is called without its value under a timeout: it must
# exit 2 at once and name the option. Then the modes that do run are exercised on
# an isolated stage, so a parser change cannot quietly break them.
#
#   bash bin/deploy_selftest.sh
export PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
export PYTHONNOUSERSITE=1
unset CDPATH WHETSTONE_SKILLS_DIR
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
STAGE="$REPO_DIR/.deploy-selftest"
DEPLOY="${DEPLOY_UNDER_TEST:-$SCRIPT_DIR/deploy.sh}"

cleanup() { rm -rf "$STAGE"; }
trap cleanup EXIT
rm -rf "$STAGE"; mkdir -p "$STAGE/src/base" "$STAGE/src/skills/demo"

pass=0; fail=0
ok()  { pass=$((pass+1)); echo "  ok  - $1"; }
bad() { fail=$((fail+1)); echo "  FAIL- $1"; }

echo "whetstone deploy selftest"
echo
echo "[args] a value-taking option with its value missing exits at once, never spins"
for opt in --dest --link --gen-claudemd --dest-file --add-import --import; do
  out="$(timeout 5 bash "$DEPLOY" "$opt" 2>&1)"; rc=$?
  if [ "$rc" = 124 ]; then
    bad "$opt with no value hung (killed after 5s)"
  elif [ "$rc" = 2 ] && printf '%s' "$out" | grep -q -- "$opt requires a value"; then
    ok "$opt with no value exits 2 and names the option"
  else
    bad "$opt with no value: exit $rc, output: $out"
  fi
done
# the realistic typo: the value missing at the END of a longer command line
out="$(timeout 5 bash "$DEPLOY" --gen-claudemd "$STAGE/src" --dest-file 2>&1)"; rc=$?
[ "$rc" = 2 ] && ok "a missing value after other options is caught too" \
              || bad "trailing missing value: exit $rc: $out"
out="$(timeout 5 bash "$DEPLOY" --bogus 2>&1)"; rc=$?
{ [ "$rc" = 2 ] && printf '%s' "$out" | grep -q "unknown arg"; } \
  && ok "an unknown option is refused" || bad "unknown option: exit $rc: $out"

echo
echo "[gen-claudemd] the mode still works after the parser change"
printf '# conduct\nrule one\n' > "$STAGE/src/base/conduct.md"
OUT="$STAGE/out/CLAUDE.md"
timeout 10 bash "$DEPLOY" --gen-claudemd "$STAGE/src" --dest-file "$OUT" >/dev/null 2>&1
if [ -f "$OUT" ] && head -1 "$OUT" | grep -q "GENERATED by whetstone deploy" \
   && [ "$(tail -n +4 "$OUT")" = "$(cat "$STAGE/src/base/conduct.md")" ]; then
  ok "generated file = header + the source, verbatim"
else
  bad "generated file is wrong"
fi
printf 'hand edit\n' >> "$OUT"
timeout 10 bash "$DEPLOY" --gen-claudemd "$STAGE/src" --dest-file "$OUT" >/dev/null 2>&1
if grep -q "hand edit" "$OUT".bak-* 2>/dev/null && ! grep -q "hand edit" "$OUT"; then
  ok "the previous file is backed up before it is replaced"
else
  bad "the previous file was not backed up"
fi
timeout 5 bash "$DEPLOY" --gen-claudemd "$STAGE/nope" --dest-file "$OUT" >/dev/null 2>&1; rc=$?
[ "$rc" = 1 ] && ok "a source without base/conduct.md is refused" || bad "missing source: exit $rc"

echo
echo "[link] a value followed by more options still parses"
printf -- '---\nname: demo\ndescription: selftest fixture\n---\n' > "$STAGE/src/skills/demo/SKILL.md"
timeout 10 bash "$DEPLOY" --link "$STAGE/src" --dest "$STAGE/skills" >/dev/null 2>&1; rc=$?
if [ "$rc" = 0 ] && [ -L "$STAGE/skills/demo" ]; then
  ok "--link <src> --dest <dir> symlinks the skill into <dir>"
else
  bad "link mode broke: exit $rc"
fi

echo
echo "[scopes] skill-scopes.tsv links a skill into project dirs instead of the global dir"
SC="$STAGE/sc"; mkdir -p "$SC/src/skills" "$SC/global" "$SC/proj-a" "$SC/proj b" "$SC/hm/ph"
for n in wide narrow other; do
  mkdir -p "$SC/src/skills/$n"; printf -- '---\nname: %s\ndescription: fixture\n---\n' "$n" > "$SC/src/skills/$n/SKILL.md"
done
abs_narrow="$(cd "$SC/src/skills/narrow" && pwd)"
ln -s "$abs_narrow" "$SC/global/narrow"                 # left over from an earlier global deploy
ln -s "$SC/elsewhere/other" "$SC/global/other"          # someone else's link: must not be touched
printf '# comment line\n\nnarrow\t%s\t%s\t~/ph\nother\t%s\n' "$SC/proj-a" "$SC/proj b" "$SC/proj-a" > "$SC/src/skill-scopes.tsv"
out="$(HOME="$SC/hm" timeout 10 bash "$DEPLOY" --link "$SC/src" --dest "$SC/global" 2>&1)"; rc=$?
[ "$rc" = 0 ] && ok "a valid scope file runs (exit 0)" || bad "valid scope file: exit $rc: $out"
{ [ "$(readlink "$SC/proj-a/.claude/skills/narrow")" = "$abs_narrow" ] && [ -L "$SC/proj b/.claude/skills/narrow" ] \
  && [ -L "$SC/hm/ph/.claude/skills/narrow" ]; } \
  && ok "a scoped skill is linked into every listed dir (a path with a space, and ~/)" || bad "scoped links missing: $out"
[ ! -e "$SC/global/narrow" ] && [ ! -L "$SC/global/narrow" ] \
  && ok "…and this repo's old global link to it is removed" || bad "global link to a scoped skill still there"
{ [ "$(readlink "$SC/global/other")" = "$SC/elsewhere/other" ] && printf '%s' "$out" | grep -q "NOTE: $SC/global/other is not this repo's link"; } \
  && ok "a global entry that is not this repo's link is left alone, and said so" || bad "foreign global entry: $out"
[ -L "$SC/global/wide" ] && [ ! -e "$SC/proj-a/.claude/skills/wide" ] \
  && ok "an unlisted skill is linked globally, as before" || bad "unlisted skill: $out"
printf '%s' "$out" | grep -q "2 scoped to project dirs (1 removed from" \
  && ok "the summary counts scoped skills and removed global links" || bad "summary: $out"
out2="$(HOME="$SC/hm" timeout 10 bash "$DEPLOY" --link "$SC/src" --dest "$SC/global" 2>&1)"
{ printf '%s' "$out2" | grep -q "0 linked, 0 relinked" && printf '%s' "$out2" | grep -q "ok (already linked): narrow"; } \
  && ok "a second run changes nothing" || bad "second run: $out2"

# a broken scope file stops the run before anything is linked
bad_case() { # $1 label, $2 scope file content
  local B="$STAGE/sc-bad"; rm -rf "$B"; mkdir -p "$B/global" "$B/p"; cp -r "$SC/src" "$B/src"
  printf "$2" "$B/p" > "$B/src/skill-scopes.tsv"
  local o r; o="$(timeout 10 bash "$DEPLOY" --link "$B/src" --dest "$B/global" 2>&1)"; r=$?
  if [ "$r" = 1 ] && [ -z "$(ls -A "$B/global")" ] && [ ! -e "$B/p/.claude" ] && printf '%s' "$o" | grep -q "nothing linked"; then
    ok "refused, nothing linked: $1"
  else
    bad "$1: exit $r, global: $(ls -A "$B/global" | tr '\n' ' '), out: $o"
  fi
}
bad_case "an unknown skill"                 'ghost\t%s\n'
bad_case "a directory that does not exist"  'narrow\t%s/missing\n'
bad_case "a skill with no directory"        'narrow\n%.0s'
bad_case "spaces instead of a TAB"          'narrow   %s\n'
rm -f "$SC/src/skill-scopes.tsv"; rm -rf "$SC/global2"
timeout 10 bash "$DEPLOY" --link "$SC/src" --dest "$SC/global2" >/dev/null 2>&1
[ -L "$SC/global2/narrow" ] && [ -L "$SC/global2/wide" ] && [ -L "$SC/global2/other" ] \
  && ok "no scope file: every skill is linked globally, as before" || bad "no scope file broke link mode"

echo
echo "summary: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
