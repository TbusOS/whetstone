#!/usr/bin/env bash
# whetstone deploy — install a skill library + generate memory files. Collision-safe.
#
# Modes (exactly one):
#   bin/deploy.sh <pack.tar.gz>              [--dest <skills-dir>] [--force] [--clean]
#       Copy mode: extract a pack.sh tarball and cp each skill into DEST.
#   bin/deploy.sh --link <src-repo>          [--dest <skills-dir>] [--force]
#       Link mode: symlink each skill under <src-repo>/skills/ into DEST.
#       Source repo stays the single source of truth; edits are live, no drift.
#       <src-repo>/skill-scopes.tsv (optional) scopes a skill to project dirs:
#         <skill><TAB><dir>[<TAB><dir> ...]     ~ allowed; lines starting with # are comments
#       A listed skill is linked into <dir>/.claude/skills/ for each dir and NOT
#       into DEST; a link to it that this repo left in DEST is removed. The whole
#       file is checked first — an unknown skill, a missing dir or a line without
#       a dir stops the run before anything is linked. Why (spec/routing.md): a
#       skill that only matters in one project should not take space in every
#       session's menu; the runtime shows it when a session starts in that dir or
#       reads a file there (Claude Code, measured 2026-09-29).
#   bin/deploy.sh --gen-claudemd <src-repo>  [--dest-file <path>]
#       Generate the always-on memory file (default ~/.claude/CLAUDE.md) from
#       <src-repo>/base/conduct.md. Existing dest is backed up first, never
#       silently overwritten. Only the always-on base is emitted; on-demand
#       skills and project-scoped shared files are NOT inlined here.
#   bin/deploy.sh --add-import <CLAUDE.md> --import <file>
#       Ensure <CLAUDE.md> imports <file> via an absolute @path line, idempotent
#       (skipped if already present). Backs up first. <file> is any shared file
#       you want pulled into that project's context (e.g. a shared conventions
#       file); the tool does not assume a specific name.
#
# Default skills dest is the Claude Code skills dir; override with --dest (or
# env WHETSTONE_SKILLS_DIR). Under --force in link mode, a replaced real dir is
# MOVED to <dest>/../skills-linkbak-<ts>/ (outside DEST, so it is not re-scanned
# as a duplicate skill) — never deleted. No /tmp: staging under the repo.

export PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
export PYTHONNOUSERSITE=1
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
STAGE="$REPO_DIR/.deploy-stage"

PACK=""; DEST="${WHETSTONE_SKILLS_DIR:-$HOME/.claude/skills}"; FORCE=0
LINK_SRC=""; GEN_SRC=""; DESTFILE=""; IMPORT_FILE=""; IMPORT_TARGET=""
# Options that take a value end in `shift 2`. In bash, `shift 2` FAILS and
# shifts NOTHING when only one argument is left, so a missing value leaves $#
# unchanged and spins this loop forever at 100% CPU. Observed for real:
# `deploy.sh --gen-claudemd` (value omitted) burned one core from 2026-08-31
# to 2026-09-03 — 76.5 hours of CPU time — before anyone noticed, because it
# holds no memory, opens no files and produces no output while spinning.
# Two layers below: need_arg rejects a missing value up front, and the
# progress check catches any future branch that forgets to shift at all.
need_arg() {  # $1 = option name, $2 = remaining arg count
  [ "$2" -ge 2 ] || { echo "deploy.sh: $1 requires a value" >&2; exit 2; }
}

while [ $# -gt 0 ]; do
  _argc_before=$#
  case "$1" in
    --dest)         need_arg "$1" $#; DEST="$2"; shift 2;;
    --force)        FORCE=1; shift;;
    --link)         need_arg "$1" $#; LINK_SRC="$2"; shift 2;;
    --gen-claudemd) need_arg "$1" $#; GEN_SRC="$2"; shift 2;;
    --dest-file)    need_arg "$1" $#; DESTFILE="$2"; shift 2;;
    --add-import)   need_arg "$1" $#; IMPORT_FILE="$2"; shift 2;;
    --import)       need_arg "$1" $#; IMPORT_TARGET="$2"; shift 2;;
    --clean)        rm -rf "$STAGE"; echo "whetstone deploy: cleaned"; exit 0;;
    -*) echo "unknown arg: $1" >&2; exit 2;;
    *)  PACK="$1"; shift;;
  esac
  [ $# -lt "$_argc_before" ] || {
    echo "deploy.sh: internal error - arg parsing made no progress at: $1" >&2
    exit 2
  }
done

# ── gen-claudemd mode: base/conduct.md → always-on memory file ────────────
if [ -n "$GEN_SRC" ]; then
  SRCF="$GEN_SRC/base/conduct.md"
  [ -f "$SRCF" ] || { echo "no base/conduct.md under: $GEN_SRC" >&2; exit 1; }
  OUT="${DESTFILE:-$HOME/.claude/CLAUDE.md}"
  TS="$(date -u +%Y%m%d-%H%M%S)"
  ABSSRC="$(cd "$(dirname "$SRCF")" && pwd)/$(basename "$SRCF")"
  if [ -f "$OUT" ]; then cp -a "$OUT" "$OUT.bak-$TS"; echo "backed up: $OUT → $OUT.bak-$TS"; fi
  mkdir -p "$(dirname "$OUT")"
  { printf '<!-- GENERATED by whetstone deploy --gen-claudemd from %s\n' "$ABSSRC"
    printf '     Edit the source, then re-run. Do NOT edit this file directly. -->\n\n'
    cat "$SRCF"
  } > "$OUT"
  echo "generated: $OUT  (from $ABSSRC)"
  exit 0
fi

# ── add-import mode: ensure a CLAUDE.md imports a shared file ─────────────
if [ -n "$IMPORT_FILE" ]; then
  [ -n "$IMPORT_TARGET" ] || { echo "--add-import needs --import <file>" >&2; exit 2; }
  [ -f "$IMPORT_FILE" ] || { echo "CLAUDE.md not found: $IMPORT_FILE" >&2; exit 1; }
  [ -f "$IMPORT_TARGET" ] || { echo "import target not found: $IMPORT_TARGET" >&2; exit 1; }
  TARGET_ABS="$(cd "$(dirname "$IMPORT_TARGET")" && pwd)/$(basename "$IMPORT_TARGET")"
  LINE="@$TARGET_ABS"
  if grep -qF "$LINE" "$IMPORT_FILE"; then
    echo "already imported: $IMPORT_FILE"; exit 0
  fi
  TS="$(date -u +%Y%m%d-%H%M%S)"
  cp -a "$IMPORT_FILE" "$IMPORT_FILE.bak-$TS"
  { echo "$LINE"; echo ""; cat "$IMPORT_FILE"; } > "$IMPORT_FILE.new" && mv "$IMPORT_FILE.new" "$IMPORT_FILE"
  echo "added import → $IMPORT_FILE  (line: $LINE, backup .bak-$TS)"
  exit 0
fi

# ── link mode: symlink each skill from <src-repo>/skills into DEST ────────
if [ -n "$LINK_SRC" ]; then
  SRC_SKILLS="$LINK_SRC/skills"
  [ -d "$SRC_SKILLS" ] || { echo "no skills/ under: $LINK_SRC" >&2; exit 1; }
  SCOPES="$LINK_SRC/skill-scopes.tsv"
  TS="$(date -u +%Y%m%d-%H%M%S)"
  linked=0; relinked=0; skipped=0; okc=0; scoped=0; unglobal=0

  # every "name<TAB>dir" pair in the scope file, ~ expanded, prefixed by its line number
  scope_pairs() {
    [ -f "$SCOPES" ] || return 0
    local n=0 line f i dir
    while IFS= read -r line || [ -n "$line" ]; do
      n=$((n+1)); line="${line%$'\r'}"
      case "$line" in ''|'#'*) continue;; esac
      IFS=$'\t' read -r -a f <<< "$line"
      if [ "${#f[@]}" -lt 2 ]; then printf '%s\t%s\t\n' "$n" "${f[0]}"; continue; fi
      for ((i=1; i<${#f[@]}; i++)); do
        dir="${f[$i]}"; [ -z "$dir" ] && continue
        case "$dir" in "~") dir="$HOME";; "~/"*) dir="$HOME/${dir#\~/}";; esac
        printf '%s\t%s\t%s\n' "$n" "${f[0]}" "$dir"
      done
    done < "$SCOPES"
  }
  scope_dirs() { scope_pairs | awk -F'\t' -v s="$1" '$2 == s && $3 != "" {print $3}'; }

  # check the whole scope file before linking anything
  if [ -f "$SCOPES" ]; then
    errs=0
    while IFS=$'\t' read -r n name dir; do
      if [ ! -f "$SRC_SKILLS/$name/SKILL.md" ]; then
        echo "skill-scopes.tsv:$n: no such skill under $SRC_SKILLS: $name" >&2; errs=$((errs+1))
      fi
      if [ -z "$dir" ]; then
        echo "skill-scopes.tsv:$n: $name has no directory after it (TAB-separated)" >&2; errs=$((errs+1))
      elif [ ! -d "$dir" ]; then
        echo "skill-scopes.tsv:$n: no such directory: $dir ($name)" >&2; errs=$((errs+1))
      fi
    done < <(scope_pairs)
    [ "$errs" -gt 0 ] && { echo "whetstone deploy --link: $errs problem(s) in $SCOPES — nothing linked" >&2; exit 1; }
  fi

  # link_one <target path> <source dir> <name>: the link-or-skip rule, for any target
  link_one() {
    local tgt="$1" abs="$2" name="$3" bak
    if [ -L "$tgt" ]; then
      if [ "$(readlink "$tgt")" = "$abs" ]; then
        echo "ok (already linked): $name → ${tgt%/*}"; okc=$((okc+1))
      else
        ln -sfn "$abs" "$tgt"; echo "relinked: $name → ${tgt%/*}"; relinked=$((relinked+1))
      fi
      return
    fi
    if [ -e "$tgt" ]; then
      if [ "$FORCE" -ne 1 ]; then
        echo "SKIP (real dir exists, use --force): $tgt"; skipped=$((skipped+1)); return
      fi
      bak="$(cd "$(dirname "$(dirname "$tgt")")" && pwd)/skills-linkbak-$TS"
      mkdir -p "$bak"; mv "$tgt" "$bak/$name"
      echo "backed up real dir → $bak/$name"
    fi
    ln -s "$abs" "$tgt"; echo "linked: $name → ${tgt%/*}"; linked=$((linked+1))
  }

  mkdir -p "$DEST"
  for d in "$SRC_SKILLS"/*/; do
    name="$(basename "$d")"
    [ -f "${d}SKILL.md" ] || continue
    abs="$(cd "$d" && pwd)"
    dirs="$(scope_dirs "$name")"
    if [ -n "$dirs" ]; then
      scoped=$((scoped+1))
      while IFS= read -r pdir; do
        mkdir -p "$pdir/.claude/skills"
        link_one "$pdir/.claude/skills/$name" "$abs" "$name"
      done <<< "$dirs"
      g="$DEST/$name"
      if [ -L "$g" ] && [ "$(readlink "$g")" = "$abs" ]; then
        rm "$g"; echo "unlinked from $DEST (scoped): $name"; unglobal=$((unglobal+1))
      elif [ -e "$g" ] || [ -L "$g" ]; then
        echo "NOTE: $g is not this repo's link — left as is, so $name still shows in every session"
      fi
      continue
    fi
    link_one "$DEST/$name" "$abs" "$name"
  done
  echo "whetstone deploy --link: $linked linked, $relinked relinked, $okc ok, $skipped skipped → $DEST;" \
       "$scoped scoped to project dirs ($unglobal removed from $DEST)"
  exit 0
fi

# ── copy mode (pack tarball) ─────────────────────────────────────────────
[ -f "$PACK" ] || { echo "pack not found: $PACK" >&2; exit 1; }
mkdir -p "$DEST"
rm -rf "$STAGE"; mkdir -p "$STAGE"
tar xzf "$PACK" -C "$STAGE"
[ -d "$STAGE/skills" ] || { echo "bad pack (no skills/)" >&2; rm -rf "$STAGE"; exit 1; }

installed=0; skipped=0
for d in "$STAGE/skills"/*/; do
  name="$(basename "$d")"
  if [ -e "$DEST/$name" ] && [ "$FORCE" -ne 1 ]; then
    echo "SKIP (exists, use --force): $name"; skipped=$((skipped+1)); continue
  fi
  rm -rf "$DEST/$name"; cp -r "$d" "$DEST/$name"
  echo "installed: $name"; installed=$((installed+1))
done
rm -rf "$STAGE"
echo "whetstone deploy: $installed installed, $skipped skipped → $DEST"
